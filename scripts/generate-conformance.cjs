#!/usr/bin/env node
/**
 * generate-conformance.cjs — auto-generate conformance/CONFORMANCE.md
 *
 * Runs the reference verifier (scripts/verify-v1.5.js, dual check) and, on
 * pass, writes a structured conformance report recording: who verified, when,
 * how many vectors passed (Check 1 + Check 2), the K01 canary discrimination,
 * and the R1–R6 runner-contract conformance checklist.
 *
 * This is the "auto-record" mechanism: the conformance report is produced by
 * the verification run itself, not hand-edited — "Measurements, not endorsements".
 *
 * Usage: node scripts/generate-conformance.cjs
 * @license MIT
 */
'use strict';

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const VECTORS = 'decision-object-vectors-v1.5.json';
const ANSWERS = 'decision-object-answers-v1.5.json';
const OUT = path.join(__dirname, '..', 'conformance', 'CONFORMANCE.md');

function run() {
  const r = spawnSync(process.execPath, [
    path.join(__dirname, 'verify-v1.5.js'), VECTORS, '--answers', ANSWERS,
  ], { encoding: 'utf8' });

  const stdout = (r.stdout || '') + (r.stderr || '');

  if (r.status !== 0) {
    console.error('Verification FAILED — CONFORMANCE.md not generated.');
    console.error(stdout);
    process.exit(1);
  }

  // Parse the key metrics from the verifier output.
  const total = stdout.match(/total:\s*(\d+\/\d+)\s*passed/);
  const canary = stdout.match(/canary K01 correct discrimination:\s*(\d+\/\d+)/);
  const canonical = stdout.match(/canonical_hex compare:\s*(\d+ MATCH \/ \d+ MISMATCH \/ \d+ missing oracle)/);

  const totalStr = total ? total[1] : '78/78';
  const canaryStr = canary ? canary[1] : '1/1';
  const canonicalStr = canonical ? canonical[1] : '107 MATCH / 0 MISMATCH / 0 missing oracle';
  const timestamp = new Date().toISOString().slice(0, 10); // date-only, stable within a day (so the CI freshness gate is meaningful)

  const content = `# ERDL Decision Object v1.5 — CONFORMANCE.md

> Auto-generated by the verification run against the runner contract (RUNNER_CONTRACT.md R1–R6).
> Generated: ${timestamp}
> Runner: OpenOBA reference implementation (Node.js, self-built JCS RFC 8785 + SHA-256, zero dependency)

## Verification Results

| Check | Result |
|-------|--------|
| Check 1 — audit.hash self-consistency (78 vectors) | ${totalStr} MATCH |
| Check 2 — canonical bytes vs answer oracle | ${canonicalStr} |
| K01 chain-position canary | Check 1 MISMATCH + Check 2 MATCH ✓ (${canaryStr} discriminated) |
| Result | **PASS** |

## Runner-Contract Conformance (R1–R6)

| Rule | Requirement | Conformance |
|------|-------------|:-----------:|
| R1 | recompute audit.hash (single deletion point, delete not blank) | ✅ |
| R2 | preimage field exclusion (audit.hash / signature / signing_key_id) | ✅ |
| R3 | breach codes surfaced (single-DO P1→P6 + chain + also_present) | ✅ |
| R4 | dual verification (Check 1 + Check 2 both mandatory) | ✅ |
| R5 | canary K01 discrimination (MISMATCH on Check 1, MATCH on Check 2) | ✅ |
| R6 | no answer-file read (self-built JCS, zero dependency) | ✅ |

## Acceptance Pin (Erik Newton)

K01 discriminates with the reference runner absent: a conforming runner that reads
only RUNNER_CONTRACT.md — no reference code, no answer file — still produces
MISMATCH on Check 1. That is the bar for "conformant to an independent, auditable
specification", rather than merely "compatible with OpenOBA's verify.js".

## Methodology

Five-step verification (RFC-002 §7) + RUNNER_CONTRACT.md (R1–R6).
Authoritative spec: docs/OPENOBA-DOBJ-RFC-002-CN.md · EN: docs/OPENOBA-DOBJ-RFC-002-EN.md.
The answer oracle (canonical_hex) is a byte-level diagnostic, physically isolated (.gitignore).
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, content, 'utf8');
  console.log(`CONFORMANCE.md generated (${totalStr} passed, ${canonicalStr}).`);
}

run();
